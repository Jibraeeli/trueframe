"""Run every check on one file and assemble the report."""

from dataclasses import asdict, dataclass
from pathlib import Path

from app.worker import frames as frame_tools
from app.worker import metadata as metadata_check
from app.worker import provenance as provenance_check
from app.worker import scoring
from app.worker.detector import Detector
from app.worker.explainer import Explainer

SUSPICIOUS_FROM = 0.5
MAX_SUSPICIOUS_FRAMES = 3

LIMITATIONS = [
    "Automated detection makes mistakes in both directions. Use this as one input, not a final answer.",
    "The model is strongest on faces fully generated by AI. It nearly always misses face swaps and edited video, so a clean result tells you almost nothing about those. It also often misses AI art.",
    "New generation techniques may not be recognised by the model.",
    "Compression, filters and screenshots can reduce accuracy.",
    "The model looks at pictures only. Audio is not checked.",
]


@dataclass(frozen=True)
class Analysis:
    report: dict
    suspicious_frames: dict[int, Path]


def _frame_entry(index: int, timestamp: float | None, probability: float) -> dict:
    return {"index": index, "timestamp": timestamp, "fake_probability": round(probability, 4)}


def analyse(
    source: Path,
    media_type: str,
    workdir: Path,
    detector: Detector,
    explainer: Explainer,
    max_frames: int,
) -> Analysis:
    provenance = provenance_check.check(source, media_type)
    metadata = metadata_check.inspect(source, media_type)
    frames = frame_tools.extract(source, media_type, workdir, max_frames)

    probabilities = [detector.fake_probability(frame.path) for frame in frames]
    overall = scoring.aggregate_probabilities(probabilities)
    score = scoring.combine(overall, len(frames), provenance, metadata)

    ranked = sorted(enumerate(probabilities), key=lambda item: item[1], reverse=True)
    suspicious = [(i, p) for i, p in ranked if p >= SUSPICIOUS_FROM][:MAX_SUSPICIOUS_FRAMES]

    report = {
        "trust_score": score.trust_score,
        "verdict": score.verdict,
        "verdict_label": score.verdict_label,
        "summary": explainer.explain(score),
        "evidence": [asdict(item) for item in score.evidence],
        "suspicious_frames": [_frame_entry(i, frames[i].timestamp, p) for i, p in suspicious],
        "checks": {
            "provenance": asdict(provenance),
            "metadata": asdict(metadata),
            "detector": {
                "model": detector.name,
                "frames_analysed": len(frames),
                "fake_probability": round(overall, 4),
                "frames": [
                    _frame_entry(i, frame.timestamp, probabilities[i])
                    for i, frame in enumerate(frames)
                ],
            },
        },
        "limitations": LIMITATIONS,
    }
    return Analysis(report, {i: frames[i].path for i, _ in suspicious})
